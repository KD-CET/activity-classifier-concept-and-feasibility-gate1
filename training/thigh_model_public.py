"""thigh_model_public.py - the THIGH model for the watch's sensor fusion, trained on public thigh
data, and exported as firmware/ActivityClassifier/activity_model_thigh.h.

Fusion on the watch (decision level, "late fusion"): every 1.5 s the wrist model (PAMAP2,
activity_model.h) and this thigh model each give a share of votes for running / sedentary /
walking; the watch averages the two and shows the activity with the most. On public data with
both sensors worn together (selfBACK, 9 people) this beat wrist alone for 9 of 9 people
(evidence/C9_fusion/).

Training data: HARTH (UCI, CC BY 4.0), 22 people, accelerometer on the right front thigh (the
thigh unit's position). No gyroscope in HARTH, so the model uses the 9 thigh features that can
be computed from an accelerometer, exactly as the thigh unit computes them:
  t_acc_mean, t_acc_std, t_acc_min, t_acc_max, t_acc_jerk, t_cadence_hz, t_cadence_power,
  t_tilt_acc_mean, t_tilt_acc_std   (tilt from the accelerometer alone, from the standing pose)
Index of each in the thigh unit's packet (thigh_packet.h): THG_IDX below.

Checks printed:
  1. leave one person out on HARTH (22 people)
  2. trained on all of HARTH, tested on the thigh sensor of the first 9 selfBACK people
     (different people, different study: an outside test)

    python thigh_model_public.py path/to/harth path/to/selfBACK [--out activity_model_thigh.h]
"""
import argparse
import glob
import os
import sys
import zlib

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import harth_thigh_check as harth          # noqa: E402  (same feature code)
import selfback_fusion_check as sb         # noqa: E402

CLASSES = ["running", "sedentary", "walking"]
FEAT = ["t_acc_mean", "t_acc_std", "t_acc_min", "t_acc_max", "t_acc_jerk",
        "t_cadence_hz", "t_cadence_power", "t_tilt_acc_mean", "t_tilt_acc_std"]
THG_IDX = [0, 1, 2, 3, 4, 8, 9, 12, 13]    # positions of FEAT in the thigh packet's 14 features


def make_model():
    return RandomForestClassifier(n_estimators=10, max_depth=6, class_weight="balanced", random_state=0)


def export_thigh_to_c(model, path, source):
    names = [str(c) for c in model.classes_]
    out = ["// activity_model_thigh.h - generated by training/" + os.path.basename(__file__) + " (or train_fusion.py).",
           f"// Do not edit by hand. Random forest: {len(model.estimators_)} trees. {source}",
           "// Input: 9 thigh features, taken from the thigh packet with THG_IDX:"]
    out += [f"//   x[{i}] = {f}  (packet f[{THG_IDX[i]}])" for i, f in enumerate(FEAT)]
    out += ["#pragma once\n", f"#define THG_N_CLASSES {len(names)}", f"#define THG_N_FEATURES {len(FEAT)}",
            "static const char *THG_CLASS_NAMES[THG_N_CLASSES] = {" + ", ".join(f'"{n}"' for n in names) + "};",
            "static const int THG_IDX[THG_N_FEATURES] = {" + ", ".join(map(str, THG_IDX)) + "};\n"]

    def node_code(t, node, depth):
        pad = "  " * depth
        if t.children_left[node] == -1:
            v = t.value[node][0]
            v = v / v.sum()
            return [pad + " ".join(f"p[{k}] += {v[k]:.6f}f;" for k in range(len(v)) if v[k] > 0)]
        lines = [pad + f"if (x[{t.feature[node]}] <= {t.threshold[node]:.17g}) {{"]
        lines += node_code(t, t.children_left[node], depth + 1)
        lines.append(pad + "} else {")
        lines += node_code(t, t.children_right[node], depth + 1)
        lines.append(pad + "}")
        return lines

    for i, est in enumerate(model.estimators_):
        out.append(f"static inline void thg_tree_{i}(const float *x, float *p) {{")
        out += node_code(est.tree_, 0, 1)
        out.append("}\n")
    out += ["// Returns the class index; prob gets the share of votes for each class.",
            "static inline int thg_predict(const float *x, float *prob) {",
            "  float p[THG_N_CLASSES] = {0};"]
    out += [f"  thg_tree_{i}(x, p);" for i in range(len(model.estimators_))]
    out += ["  int best = 0;", "  for (int k = 0; k < THG_N_CLASSES; k++) {",
            f"    p[k] /= {len(model.estimators_)}.0f;", "    if (p[k] > p[best]) best = k;",
            "    if (prob) prob[k] = p[k];", "  }", "  return best;", "}"]
    mid = zlib.crc32("\n".join(out).encode())
    out.insert(out.index("#pragma once\n") + 1, f"#define THG_MODEL_ID 0x{mid:08X}u")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    return mid


def main():
    p = argparse.ArgumentParser()
    p.add_argument("harth")
    p.add_argument("selfback")
    p.add_argument("--out", default="activity_model_thigh.h")
    a = p.parse_args()

    files = sorted(glob.glob(os.path.join(a.harth, "S*.csv")))
    h = pd.concat([harth.subject_windows(f) for f in files], ignore_index=True)
    h = h.rename(columns={c: "t_" + c for c in harth.ACC})
    h = h.rename(columns={"tilt_mean": "t_tilt_acc_mean", "tilt_std": "t_tilt_acc_std"})
    print(f"HARTH: {len(h)} windows, {h.subject.nunique()} people")

    errs = {}
    for s in sorted(h.subject.unique()):
        tr, te = h.subject != s, h.subject == s
        m = make_model().fit(h.loc[tr, FEAT].to_numpy(), h.loc[tr, "label"])
        errs[s] = 100 * np.mean(m.predict(h.loc[te, FEAT].to_numpy()) != h.loc[te, "label"])
    e = pd.Series(errs)
    print(f"1. Leave one person out on HARTH: mean error {e.mean():.1f} %, worst {e.max():.1f} % ({e.idxmax()})")

    final = make_model().fit(h[FEAT].to_numpy(), h["label"])
    if list(final.classes_) != CLASSES:
        sys.exit(f"class order {list(final.classes_)} differs from the watch {CLASSES}")

    wt = os.path.join(a.selfback, "wt")
    ids = sorted({f.split("_")[0] for f in os.listdir(wt) if not f.startswith(".")})[:9]
    s9 = pd.concat([sb.person_windows(wt, pid) for pid in ids], ignore_index=True)
    s9 = s9.rename(columns={"t_tilt_mean": "t_tilt_acc_mean", "t_tilt_std": "t_tilt_acc_std"})
    pred = final.predict(s9[FEAT].to_numpy())
    per = s9.assign(wrong=pred != s9["label"]).groupby("person")["wrong"].mean() * 100
    print(f"2. Trained on HARTH, tested on selfBACK (9 people, outside test): mean error {per.mean():.1f} %, "
          f"worst {per.max():.1f} % ({per.idxmax()})")
    print("   by person: " + ", ".join(f"{k} {v:.1f}" for k, v in per.items()))
    tab = pd.crosstab(s9["label"], pred, rownames=["true"], colnames=["predicted"])
    print(tab.to_string())

    mid = export_thigh_to_c(final, a.out, "Trained on HARTH (22 people, thigh accelerometer).")
    nodes = sum(t.tree_.node_count for t in final.estimators_)
    print(f"\nWrote {a.out}: {nodes} nodes, id 0x{mid:08X}")


if __name__ == "__main__":
    main()
